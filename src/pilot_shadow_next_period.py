def _previous_period(period: str) -> str:
    number = _period_number(period) - 1
    if number < 0:
        raise PilotShadowNextPeriodError("next-period predecessor is invalid")
    year, month_index = divmod(number, 12)
    return f"{year:04d}-{month_index + 1:02d}"


def _period_parent(activation_root: Path) -> tuple[Path, bool]:
    parent = activation_root / PERIOD_WORKSPACE_DIRECTORY
    if parent.exists() or parent.is_symlink():
        if parent.is_symlink() or not parent.is_dir() or parent.resolve() != parent:
            raise PilotShadowNextPeriodError(
                "next-period workspace parent must be a real directory"
            )
        if os.name != "nt" and stat.S_IMODE(parent.stat().st_mode) != 0o700:
            raise PilotShadowNextPeriodError(
                "next-period workspace parent must use mode 0700"
            )
        return parent, False
    return parent, True


def _inspect_private_tree(root: Path) -> tuple[int, int]:
    directory_count = 0
    file_count = 0
    total_bytes = 0
    for path in root.rglob("*"):
        metadata = path.lstat()
        if stat.S_ISLNK(metadata.st_mode):
            raise PilotShadowNextPeriodError(
                "next-period workspace must not contain symbolic links"
            )
        if stat.S_ISDIR(metadata.st_mode):
            directory_count += 1
            if os.name != "nt" and stat.S_IMODE(metadata.st_mode) != 0o700:
                raise PilotShadowNextPeriodError(
                    "next-period workspace directories must use mode 0700"
                )
            continue
        if not stat.S_ISREG(metadata.st_mode):
            raise PilotShadowNextPeriodError(
                "next-period workspace may contain only regular files"
            )
        file_count += 1
        total_bytes += metadata.st_size
        if (
            file_count > MAX_FILES
            or metadata.st_size > MAX_FILE_BYTES
            or total_bytes > MAX_TOTAL_BYTES
        ):
            raise PilotShadowNextPeriodError(
                "next-period workspace exceeds its private file boundary"
            )
        if os.name != "nt" and stat.S_IMODE(metadata.st_mode) != 0o600:
            raise PilotShadowNextPeriodError(
                "next-period workspace files must use mode 0600"
            )
    return directory_count, file_count


def _read_json(path: Path, *, label: str) -> dict[str, Any]:
    if path.is_symlink() or not path.is_file():
        raise PilotShadowNextPeriodError(f"{label} must be a regular file")
    if path.stat().st_size <= 0 or path.stat().st_size > 2 * 1024 * 1024:
        raise PilotShadowNextPeriodError(f"{label} exceeds its size boundary")
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise PilotShadowNextPeriodError(f"{label} must contain valid JSON") from exc
    if not isinstance(value, dict):
        raise PilotShadowNextPeriodError(f"{label} must be a JSON object")
    return value


def initialize_next_pilot_shadow_period(
    runtime: BoxRuntime,
    config_path: str | Path,
    activation_root: str | Path,
    *,
    prepared_by: str,
    facts_as_of: str,
) -> dict[str, Any]:
    """Create the exact next monthly workspace after a verified archived period."""
    current_as_of = _facts_as_of(facts_as_of)
    root, activation_manifest, _, activation_verification = (
        _load_activation_workspace(runtime, activation_root)
    )
    config = Path(config_path).expanduser().resolve()
    if not config.is_file():
        raise PilotShadowNextPeriodError(
            "next-period Box config must be an existing regular file"
        )
    evidence_root = root / "pilot" / "series-periods"
    runs_root = root / "pipeline-runs"
    archived = _load_pilot_shadow_period_archive(
        runtime, evidence_root, runs_root, as_of=current_as_of,
    )
    latest = archived[-1]
    if archived[0]["period"] != activation_manifest["period"]:
        raise PilotShadowNextPeriodError(
            "archived period chain must start with the activation workspace period"
        )
    if not latest["ready_for_next_shadow_period"]:
        raise PilotShadowNextPeriodError(
            "latest archived Shadow observation is not ready for the next period"
        )
    if len(archived) >= MAXIMUM_PERIODS:
        raise PilotShadowNextPeriodError(
            "pilot Shadow archive reached its 24-period capacity"
        )
    period = _next_period(latest["period"])
    parent, parent_created = _period_parent(root)
    destination = parent / period
    if destination.exists() or destination.is_symlink():
        raise PilotShadowNextPeriodError(
            "next-period workspace already exists; refusing to overwrite"
        )
    entity_ids = sorted(runtime.entities.ids())
    paths = _paths(root, destination, multi_entity=len(entity_ids) > 1)
    readiness = build_pilot_readiness_workpaper(
        runtime, period=period, prepared_by=prepared_by,
    )
    readiness_body = _canonical_json_bytes(readiness)
    environment_body = _environment_body(paths)
    commands_body = _canonical_json_bytes(_commands(
        runtime,
        config,
        root,
        destination,
        period=period,
        facts_as_of=current_as_of,
    ))
    created = False
    try:
        if parent_created:
            _mkdir_private(parent)
        _mkdir_private(destination)
        created = True
        for relative in DIRECTORIES:
            _mkdir_private(destination / relative)
        initial_files = []
        for relative, body, kind, mutable in (
            (
                "readiness/workpaper.json", readiness_body,
                "mutable_period_readiness_workpaper", True,
            ),
            (ENV_NAME, environment_body, "immutable_private_path_contract", False),
            (COMMANDS_NAME, commands_body, "immutable_period_command_contract", False),
        ):
            _write_exclusive(destination / relative, body)
            initial_files.append({
                "relative_path": relative,
                "kind": kind,
                "mutable": mutable,
                "initial_sha256": _sha256(body),
            })
        manifest = {
            "schema_version": 1,
            "artifact_type": "pilot_shadow_next_period_workspace",
            "runtime_fingerprint": runtime.snapshot()["fingerprint"],
            "activation_workspace_manifest_sha256": activation_verification[
                "workspace_manifest_sha256"
            ],
            "first_archived_period": archived[0]["period"],
            "previous_archive_period_count": len(archived),
            "previous_period": latest["period"],
            "previous_observation_receipt_fingerprint": latest[
                "observation_receipt_fingerprint"
            ],
            "previous_source_bundle_fingerprint": latest[
                "source_bundle_fingerprint"
            ],
            "period": period,
            "facts_as_of": current_as_of,
            "created_at": datetime.now(timezone.utc).isoformat().replace(
                "+00:00", "Z"
            ),
            "prepared_by": prepared_by,
            "entity_ids": entity_ids,
            "directory_contract": list(DIRECTORIES),
            "initial_files": initial_files,
            "credentials_included": False,
            "raw_financial_source_files_copied": False,
            "commands_executed": False,
            "posting_authorized": False,
            "payment_authorized": False,
            "period_close_authorized": False,
            "external_filing_authorized": False,
            "external_actions_performed": False,
        }
        manifest_body = _canonical_json_bytes(manifest)
        _write_exclusive(destination / MANIFEST_NAME, manifest_body)
    except Exception:
        if created and destination.is_dir() and not destination.is_symlink():
            shutil.rmtree(destination)
        if parent_created and parent.is_dir() and not any(parent.iterdir()):
            parent.rmdir()
        raise
    return {
        "schema_version": 1,
        "initialized": True,
        "runtime_fingerprint": runtime.snapshot()["fingerprint"],
        "previous_period": latest["period"],
        "period": period,
        "entity_count": len(entity_ids),
        "multi_entity": len(entity_ids) > 1,
        "directory_count": len(DIRECTORIES),
        "initial_file_count": len(initial_files) + 1,
        "prior_archive_reverified": True,
        "new_period_readiness_template_created": True,
        "output_path_returned": False,
        "previous_archive_hashes_returned": False,
        "actors_returned": False,
        "credentials_included": False,
        "raw_financial_source_files_copied": False,
        "commands_executed": False,
        "posting_authorized": False,
        "payment_authorized": False,
        "period_close_authorized": False,
        "external_filing_authorized": False,
        "external_actions_performed": False,
    }


def verify_next_pilot_shadow_period(
    runtime: BoxRuntime,
    activation_root: str | Path,
    period: str,
    *,
    as_of: str | None = None,
) -> dict[str, Any]:
    """Verify one generated monthly workspace and its exact archived predecessor."""
    _period_number(period)
    current_as_of = _facts_as_of(as_of) if as_of is not None else None
    root, activation_manifest, _, activation_verification = (
        _load_activation_workspace(runtime, activation_root)
    )
    period_parent = root / PERIOD_WORKSPACE_DIRECTORY
    destination = period_parent / period
    if (
        period_parent.is_symlink()
        or not period_parent.is_dir()
        or period_parent.resolve() != period_parent
        or destination.is_symlink()
        or not destination.is_dir()
        or destination.resolve() != destination
    ):
        raise PilotShadowNextPeriodError(
            "next-period workspace must be an existing real derived directory"
        )
    if os.name != "nt" and (
        stat.S_IMODE(period_parent.stat().st_mode) != 0o700
        or stat.S_IMODE(destination.stat().st_mode) != 0o700
    ):
        raise PilotShadowNextPeriodError(
            "next-period workspace root and parent must use mode 0700"
        )
    directory_count, file_count = _inspect_private_tree(destination)
    manifest_path = destination / MANIFEST_NAME
    manifest = _read_json(manifest_path, label="next-period workspace manifest")
    expected_fields = {
        "schema_version", "artifact_type", "runtime_fingerprint",
        "activation_workspace_manifest_sha256", "first_archived_period",
        "previous_archive_period_count", "previous_period",
        "previous_observation_receipt_fingerprint",
        "previous_source_bundle_fingerprint", "period", "facts_as_of",
        "created_at", "prepared_by", "entity_ids", "directory_contract",
        "initial_files", "credentials_included",
        "raw_financial_source_files_copied", "commands_executed",
        "posting_authorized", "payment_authorized", "period_close_authorized",
        "external_filing_authorized", "external_actions_performed",
    }
    if set(manifest) != expected_fields:
        raise PilotShadowNextPeriodError(
            "next-period workspace manifest fields are invalid"
        )
    entity_ids = sorted(runtime.entities.ids())
    if (
        manifest.get("schema_version") != 1
        or manifest.get("artifact_type") != "pilot_shadow_next_period_workspace"
        or manifest.get("runtime_fingerprint") != runtime.snapshot()["fingerprint"]
        or manifest.get("activation_workspace_manifest_sha256")
        != activation_verification["workspace_manifest_sha256"]
        or manifest.get("first_archived_period") != activation_manifest["period"]
        or manifest.get("period") != period
        or manifest.get("previous_period") != _previous_period(period)
        or manifest.get("entity_ids") != entity_ids
        or manifest.get("directory_contract") != list(DIRECTORIES)
    ):
        raise PilotShadowNextPeriodError(
            "next-period workspace does not match the current Box or activation root"
        )
    _facts_as_of(str(manifest.get("facts_as_of") or ""))
    if current_as_of is not None and current_as_of < manifest["facts_as_of"]:
        raise PilotShadowNextPeriodError(
            "next-period reverification date must not predate initialization"
        )
    try:
        created_at = datetime.fromisoformat(
            str(manifest.get("created_at") or "").replace("Z", "+00:00")
        )
    except ValueError as exc:
        raise PilotShadowNextPeriodError(
            "next-period workspace created_at must be an ISO date-time"
        ) from exc
    if created_at.tzinfo is None:
        raise PilotShadowNextPeriodError(
            "next-period workspace created_at must include a timezone"
        )
    for field in (
        "credentials_included", "raw_financial_source_files_copied",
        "commands_executed", "posting_authorized", "payment_authorized",
        "period_close_authorized", "external_filing_authorized",
        "external_actions_performed",
    ):
        if manifest.get(field) is not False:
            raise PilotShadowNextPeriodError(
                f"next-period workspace manifest {field} must remain false"
            )
    for relative in DIRECTORIES:
        directory = destination / relative
        if directory.is_symlink() or not directory.is_dir():
            raise PilotShadowNextPeriodError(
                "next-period workspace required directory is missing"
            )
    initial_files = manifest.get("initial_files")
    if not isinstance(initial_files, list) or len(initial_files) != 3:
        raise PilotShadowNextPeriodError(
            "next-period workspace initial file contract is invalid"
        )
    expected_initial_contract = {
        "readiness/workpaper.json": (
            "mutable_period_readiness_workpaper", True,
        ),
        ENV_NAME: ("immutable_private_path_contract", False),
        COMMANDS_NAME: ("immutable_period_command_contract", False),
    }
    if {
        item.get("relative_path"): (item.get("kind"), item.get("mutable"))
        for item in initial_files if isinstance(item, dict)
    } != expected_initial_contract:
        raise PilotShadowNextPeriodError(
            "next-period workspace initial file scope changed"
        )
    for item in initial_files:
        if not isinstance(item, dict) or set(item) != {
            "relative_path", "kind", "mutable", "initial_sha256",
        }:
            raise PilotShadowNextPeriodError(
                "next-period workspace initial file entry is invalid"
            )
        relative = item.get("relative_path")
        if not isinstance(relative, str) or Path(relative).is_absolute():
            raise PilotShadowNextPeriodError(
                "next-period workspace initial file path is invalid"
            )
        candidate = (destination / relative).resolve()
        try:
            candidate.relative_to(destination)
        except ValueError as exc:
            raise PilotShadowNextPeriodError(
                "next-period workspace initial file escapes its root"
            ) from exc
        if not candidate.is_file() or candidate.is_symlink():
            raise PilotShadowNextPeriodError(
                "next-period workspace initial file is missing"
            )
        if item.get("mutable") is False and _sha256(
            candidate.read_bytes()
        ) != item.get("initial_sha256"):
            raise PilotShadowNextPeriodError(
                "next-period workspace immutable file changed"
            )
    readiness = _read_json(
        destination / "readiness" / "workpaper.json",
        label="next-period readiness workpaper",
    )
    if (
        readiness.get("runtime_fingerprint") != runtime.snapshot()["fingerprint"]
        or readiness.get("period") != period
        or readiness.get("prepared_by") != manifest.get("prepared_by")
        or readiness.get("contains_credentials") is not False
        or readiness.get("contains_raw_source_identifiers") is not False
        or readiness.get("contains_raw_tax_identifiers") is not False
        or readiness.get("contains_financial_values") is not False
        or readiness.get("external_actions_authorized") is not False
    ):
        raise PilotShadowNextPeriodError(
            "next-period readiness workpaper violates its private boundary"
        )
    expected_environment = _environment_body(_paths(
        root, destination, multi_entity=len(entity_ids) > 1,
    ))
    if (destination / ENV_NAME).read_bytes() != expected_environment:
        raise PilotShadowNextPeriodError(
            "next-period private path contract changed"
        )
    commands = _read_json(
        destination / COMMANDS_NAME, label="next-period command contract",
    )
    expected_commands = _commands(
        runtime,
        runtime.config_path.expanduser().resolve(),
        root,
        destination,
        period=period,
        facts_as_of=str(manifest["facts_as_of"]),
    )
    if commands != expected_commands:
        raise PilotShadowNextPeriodError(
            "next-period command contract changed from the current Box template"
        )
    prior_count = manifest.get("previous_archive_period_count")
    if not isinstance(prior_count, int) or not 1 <= prior_count <= MAXIMUM_PERIODS:
        raise PilotShadowNextPeriodError(
            "next-period predecessor archive coverage changed"
        )
    archive = _load_pilot_shadow_period_archive(
        runtime,
        root / "pilot" / "series-periods",
        root / "pipeline-runs",
        as_of=str(manifest["facts_as_of"]),
        period_count=prior_count,
    )
    if (
        len(archive) != prior_count
        or archive[0]["period"] != manifest["first_archived_period"]
    ):
        raise PilotShadowNextPeriodError(
            "next-period predecessor archive coverage changed"
        )
    predecessor = archive[prior_count - 1]
    if (
        predecessor["period"] != manifest["previous_period"]
        or predecessor["observation_receipt_fingerprint"]
        != manifest["previous_observation_receipt_fingerprint"]
        or predecessor["source_bundle_fingerprint"]
        != manifest["previous_source_bundle_fingerprint"]
        or not predecessor["ready_for_next_shadow_period"]
    ):
        raise PilotShadowNextPeriodError(
            "next-period predecessor no longer matches the verified archive"
        )
    return {
        "schema_version": 1,
        "valid": True,
        "runtime_fingerprint": runtime.snapshot()["fingerprint"],
        "previous_period": manifest["previous_period"],
        "period": period,
        "entity_count": len(entity_ids),
        "multi_entity": len(entity_ids) > 1,
        "directory_count": directory_count,
        "file_count": file_count,
        "prior_archive_reverified": True,
        "prior_archive_binding_current": True,
        "immutable_command_contract_current": True,
        "readiness_private_boundary_valid": True,
        "paths_returned": False,
        "previous_archive_hashes_returned": False,
        "actors_returned": False,
        "credentials_returned": False,
        "financial_values_returned": False,
        "commands_executed": False,
        "posting_authorized": False,
        "payment_authorized": False,
        "period_close_authorized": False,
        "external_filing_authorized": False,
        "external_actions_performed": False,
    }
