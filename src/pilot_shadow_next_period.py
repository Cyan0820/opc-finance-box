def _environment_body(paths: Mapping[str, Path]) -> bytes:
    lines = [
        "# Generated by opc-finance-box pilot-shadow-next-period-init.",
        "# Contains private artifact paths only; credentials remain in a secret manager.",
    ]
    for name in sorted(paths):
        lines.append(f"{name}={shlex.quote(str(paths[name]))}")
    lines.extend([
        "",
        "# This file does not authorize posting, payment, period close or filing.",
    ])
    return ("\n".join(lines) + "\n").encode("utf-8")


