class PilotShadowNextPeriodError(RuntimeError):
    """Raised when the next private Pilot Shadow period cannot be initialized."""


def _canonical_json_bytes(value: Any) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def _sha256(body: bytes) -> str:
    return hashlib.sha256(body).hexdigest()


def _mkdir_private(path: Path) -> None:
    path.mkdir(mode=0o700)
    if os.name != "nt":
        path.chmod(0o700)


def _write_exclusive(path: Path, body: bytes) -> None:
    try:
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError as exc:
        raise PilotShadowNextPeriodError(
            f"next-period workspace file already exists: {path.name}"
        ) from exc
    try:
        if os.name != "nt":
            os.fchmod(descriptor, 0o600)
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(body)
            stream.flush()
            os.fsync(stream.fileno())
    except Exception:
        path.unlink(missing_ok=True)
        raise


def _facts_as_of(value: str) -> str:
    text = str(value or "")
    try:
        parsed = date.fromisoformat(text)
    except ValueError as exc:
        raise PilotShadowNextPeriodError(
            "next-period facts_as_of must use YYYY-MM-DD"
        ) from exc
    if parsed.isoformat() != text:
        raise PilotShadowNextPeriodError(
            "next-period facts_as_of must use canonical YYYY-MM-DD"
        )
    return text


def _next_period(period: str) -> str:
    number = _period_number(period) + 1
    year, month_index = divmod(number, 12)
    return f"{year:04d}-{month_index + 1:02d}"


def _command(step_id: str, purpose: str, argv: list[str]) -> dict[str, Any]:
    return {
        "step_id": step_id,
        "purpose": purpose,
        "action": "run_cli",
        "argv": argv,
        "shell_preview": shlex.join(argv),
        "requires_operator_edit": any(
            "REPLACE_WITH_" in argument for argument in argv
        ),
        "command_executed": False,
    }


